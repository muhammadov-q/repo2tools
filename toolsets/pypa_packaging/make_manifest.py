"""Write manifest.json for the hand-made packaging tools, so the scripts for generated tool sets work on them too.

    uv run python collect_reference_traces.py out/packaging/exercises.jsonl -o out/traces/reference-function.jsonl -- uv run python toolsets/pypa_packaging/server.py
    python3 -I toolsets/pypa_packaging/make_manifest.py out/traces/reference-function.jsonl

A manifest lists each tool with sample inputs. The samples come from the calls of the exercises'
known-good solutions; the six tools no exercise uses get a few samples written here.
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SET = "pypa-packaging-handmade"
WRAPS = {"is_valid_version": "packaging.version.Version", "normalize_version": "packaging.version.Version", "version_info": "packaging.version.Version",
         "base_version": "packaging.version.Version.base_version", "compare_versions": "packaging.version.Version", "sort_versions": "packaging.version.Version",
         "canonicalize_version": "packaging.utils.canonicalize_version", "is_valid_specifier": "packaging.specifiers.SpecifierSet",
         "version_satisfies": "packaging.specifiers.SpecifierSet.contains", "filter_versions": "packaging.specifiers.SpecifierSet.filter",
         "combine_specifiers": "packaging.specifiers.SpecifierSet", "is_satisfiable": "packaging.specifiers.SpecifierSet.is_unsatisfiable",
         "specifier_is_subset": "packaging.specifiers.SpecifierSet.is_subset", "specifiers_overlap": "packaging.specifiers.SpecifierSet.is_disjoint",
         "parse_requirement": "packaging.requirements.Requirement", "evaluate_marker": "packaging.markers.Marker.evaluate",
         "canonicalize_name": "packaging.utils.canonicalize_name", "parse_wheel_filename": "packaging.utils.parse_wheel_filename",
         "parse_sdist_filename": "packaging.utils.parse_sdist_filename", "parse_tag": "packaging.tags.parse_tag", "supported_tags": "packaging.tags.compatible_tags"}
EXTRA = {
    "is_valid_specifier": [{"specifier": ">=1.0,<2"}, {"specifier": "~=2.2"}, {"specifier": "==1.*"}, {"specifier": "not a specifier"}],
    "combine_specifiers": [{"specifier_a": ">=1.0", "specifier_b": "<2"}, {"specifier_a": "!=1.5", "specifier_b": "~=1.4"}, {"specifier_a": ">=3.9", "specifier_b": "<3.13"}],
    "specifiers_overlap": [{"specifier_a": ">=1.0", "specifier_b": "<2"}, {"specifier_a": "<1.0", "specifier_b": ">=2"}, {"specifier_a": "==1.5", "specifier_b": ">=1.0,<2"}],
    "parse_sdist_filename": [{"filename": "requests-2.32.3.tar.gz"}, {"filename": "numpy-2.1.3.tar.gz"}, {"filename": "typing_extensions-4.12.2.tar.gz"}],
    "parse_tag": [{"tag": "py3-none-any"}, {"tag": "cp312-cp312-manylinux_2_17_x86_64"}, {"tag": "py2.py3-none-any"}],
    "supported_tags": [{"python_version": "3.12", "platforms": ["manylinux_2_17_x86_64"]}, {"python_version": "3.11", "platforms": ["macosx_11_0_arm64"]},
                       {"python_version": "3.10", "platforms": ["win_amd64", "linux_x86_64"]}],
}
PER_TOOL = 10


def main() -> None:
    samples: dict[str, list] = {name: list(values) for name, values in EXTRA.items()}
    for line in open(sys.argv[1], encoding="utf-8"):
        trace = json.loads(line)
        last = trace["requests"][-1]
        for message in last["messages"]:
            for call in message.get("tool_calls") or []:
                arguments = json.loads(call["function"]["arguments"])
                known = samples.setdefault(call["function"]["name"], [])
                if arguments not in known and len(known) < PER_TOOL:
                    known.append(arguments)
    missing = sorted(set(WRAPS) - set(samples))
    if missing:
        raise SystemExit(f"no samples for: {missing}")
    manifest = {"set": SET, "url": "https://github.com/pypa/packaging", "commit": "c1d2a9d8f5ca7cc11b7d2e902ed5ee3e255e8560", "package": "packaging",
                "note": "reference tools, not generated by repo2tools.py",
                "tools": [{"name": name, "wraps": WRAPS[name], "samples": samples[name]} for name in WRAPS]}
    (HERE / "manifest.json").write_text(json.dumps(manifest, indent=1) + "\n", encoding="utf-8")
    print(f"{HERE / 'manifest.json'}: {len(manifest['tools'])} tools, {sum(len(t['samples']) for t in manifest['tools'])} samples")


if __name__ == "__main__":
    main()
